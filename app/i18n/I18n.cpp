I18n::I18n() = default;

I18n &I18n::instance() {
  static I18n s_instance;
  return s_instance;
}

void I18n::setLanguage(Language lang) {
  language_ = lang;
}

I18n::Language I18n::language() const {
  return language_;
}

QString I18n::translate(const char *sourceText) const {
  if (!sourceText) return QString();
  if (language_ == Language::English) {
    return QString::fromUtf8(sourceText);
  }

  const std::string_view key(sourceText);
  if (language_ == Language::Russian) {
    const auto it = kRussian.find(key);
    if (it != kRussian.end()) {
      return QString::fromUtf8(it->second);
    }
  } else if (language_ == Language::Ukrainian) {
    const auto it = kUkrainian.find(key);
    if (it != kUkrainian.end()) {
      return QString::fromUtf8(it->second);
    }
  }

  return QString::fromUtf8(sourceText);
}
